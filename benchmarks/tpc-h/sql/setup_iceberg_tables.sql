-- TPC-H iceberg tables setup (per scale factor)
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS {{SOLUTION_NAME}}_BENCH_DB;
USE DATABASE {{SOLUTION_NAME}}_BENCH_DB;

CREATE SCHEMA IF NOT EXISTS TPCH_SF{{SCALE}}_ICE;
USE SCHEMA TPCH_SF{{SCALE}}_ICE;

CREATE OR REPLACE WAREHOUSE {{SOLUTION_NAME}}_BENCH_WH_LOAD
  WAREHOUSE_SIZE = '{{LOAD_WH_SIZE}}'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = FALSE;

USE WAREHOUSE {{SOLUTION_NAME}}_BENCH_WH_LOAD;

CREATE OR REPLACE ICEBERG TABLE LINEITEM
  CLUSTER BY (L_SHIPDATE)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = '{{EXTERNAL_VOLUME}}'
  TARGET_FILE_SIZE = '{{TARGET_FILE_SIZE}}'
  AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF{{SCALE}}.LINEITEM;

