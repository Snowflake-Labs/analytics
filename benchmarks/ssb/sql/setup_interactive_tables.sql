-- SSB interactive tables setup (per scale factor)
-- Requires: setup_source_views.sql (SSB views derived from SNOWFLAKE_SAMPLE_DATA.TPCH_SF<scale>).
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS {{SOLUTION_NAME}}_BENCH_DB;
USE DATABASE {{SOLUTION_NAME}}_BENCH_DB;

CREATE SCHEMA IF NOT EXISTS SSB_SF{{SCALE}}_IT;
USE SCHEMA SSB_SF{{SCALE}}_IT;

CREATE OR REPLACE WAREHOUSE {{SOLUTION_NAME}}_BENCH_WH_LOAD
  WAREHOUSE_SIZE = '{{LOAD_WH_SIZE}}'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = FALSE;

USE WAREHOUSE {{SOLUTION_NAME}}_BENCH_WH_LOAD;

-- LINEORDER / LINEORDER_FLAT are clustered by order date: every SSB query
-- restricts or groups by time, and the paper (section 3.2) suggests a time sort.

CREATE OR REPLACE INTERACTIVE TABLE LINEORDER CLUSTER BY (LO_ORDERDATE)(
  LO_ORDERKEY NUMBER(38,0) NOT NULL,
  LO_LINENUMBER NUMBER(38,0) NOT NULL,
  LO_CUSTKEY NUMBER(38,0),
  LO_PARTKEY NUMBER(38,0),
  LO_SUPPKEY NUMBER(38,0),
  LO_ORDERDATE NUMBER(38,0),
  LO_ORDERPRIORITY VARCHAR(15),
  LO_SHIPPRIORITY VARCHAR(1),
  LO_QUANTITY NUMBER(38,0),
  LO_EXTENDEDPRICE NUMBER(15,2),
  LO_ORDTOTALPRICE NUMBER(15,2),
  LO_DISCOUNT NUMBER(38,0),
  LO_REVENUE NUMBER(15,2),
  LO_SUPPLYCOST NUMBER(15,2),
  LO_TAX NUMBER(38,0),
  LO_COMMITDATE NUMBER(38,0),
  LO_SHIPMODE VARCHAR(10),
    PRIMARY KEY (LO_ORDERKEY, LO_LINENUMBER) RELY
) AS SELECT * FROM SSB_SF{{SCALE}}_SRC.LINEORDER ORDER BY LO_ORDERDATE;

CREATE OR REPLACE INTERACTIVE TABLE CUSTOMER CLUSTER BY (C_CUSTKEY)(
  C_CUSTKEY NUMBER(38,0) NOT NULL,
  C_NAME VARCHAR(25),
  C_ADDRESS VARCHAR(25),
  C_CITY VARCHAR(10),
  C_NATION VARCHAR(15),
  C_REGION VARCHAR(12),
  C_PHONE VARCHAR(15),
  C_MKTSEGMENT VARCHAR(10),
    PRIMARY KEY (C_CUSTKEY) RELY
) AS SELECT * FROM SSB_SF{{SCALE}}_SRC.CUSTOMER ORDER BY C_CUSTKEY;

CREATE OR REPLACE INTERACTIVE TABLE SUPPLIER CLUSTER BY (S_SUPPKEY)(
  S_SUPPKEY NUMBER(38,0) NOT NULL,
  S_NAME VARCHAR(25),
  S_ADDRESS VARCHAR(25),
  S_CITY VARCHAR(10),
  S_NATION VARCHAR(15),
  S_REGION VARCHAR(12),
  S_PHONE VARCHAR(15),
    PRIMARY KEY (S_SUPPKEY) RELY
) AS SELECT * FROM SSB_SF{{SCALE}}_SRC.SUPPLIER ORDER BY S_SUPPKEY;

CREATE OR REPLACE INTERACTIVE TABLE PART CLUSTER BY (P_PARTKEY)(
  P_PARTKEY NUMBER(38,0) NOT NULL,
  P_NAME VARCHAR(22),
  P_MFGR VARCHAR(6),
  P_CATEGORY VARCHAR(7),
  P_BRAND1 VARCHAR(9),
  P_COLOR VARCHAR(11),
  P_TYPE VARCHAR(25),
  P_SIZE NUMBER(38,0),
  P_CONTAINER VARCHAR(10),
    PRIMARY KEY (P_PARTKEY) RELY
) AS SELECT * FROM SSB_SF{{SCALE}}_SRC.PART ORDER BY P_PARTKEY;

CREATE OR REPLACE INTERACTIVE TABLE DATES CLUSTER BY (D_DATEKEY)(
  D_DATEKEY NUMBER(38,0) NOT NULL,
  D_DATE VARCHAR(18),
  D_DAYOFWEEK VARCHAR(9),
  D_MONTH VARCHAR(9),
  D_YEAR NUMBER(38,0),
  D_YEARMONTHNUM NUMBER(38,0),
  D_YEARMONTH VARCHAR(7),
  D_DAYNUMINWEEK NUMBER(38,0),
  D_DAYNUMINMONTH NUMBER(38,0),
  D_DAYNUMINYEAR NUMBER(38,0),
  D_MONTHNUMINYEAR NUMBER(38,0),
  D_WEEKNUMINYEAR NUMBER(38,0),
  D_SELLINGSEASON VARCHAR(12),
  D_LASTDAYINWEEKFL NUMBER(1,0),
  D_LASTDAYINMONTHFL NUMBER(1,0),
  D_HOLIDAYFL NUMBER(1,0),
  D_WEEKDAYFL NUMBER(1,0),
    PRIMARY KEY (D_DATEKEY) RELY
) AS SELECT * FROM SSB_SF{{SCALE}}_SRC.DATES ORDER BY D_DATEKEY;

CREATE OR REPLACE INTERACTIVE TABLE LINEORDER_FLAT CLUSTER BY (LO_ORDERDATE)(
  LO_ORDERKEY NUMBER(38,0) NOT NULL,
  LO_LINENUMBER NUMBER(38,0) NOT NULL,
  LO_CUSTKEY NUMBER(38,0),
  LO_PARTKEY NUMBER(38,0),
  LO_SUPPKEY NUMBER(38,0),
  LO_ORDERDATE NUMBER(38,0),
  LO_ORDERPRIORITY VARCHAR(15),
  LO_SHIPPRIORITY VARCHAR(1),
  LO_QUANTITY NUMBER(38,0),
  LO_EXTENDEDPRICE NUMBER(15,2),
  LO_ORDTOTALPRICE NUMBER(15,2),
  LO_DISCOUNT NUMBER(38,0),
  LO_REVENUE NUMBER(15,2),
  LO_SUPPLYCOST NUMBER(15,2),
  LO_TAX NUMBER(38,0),
  LO_COMMITDATE NUMBER(38,0),
  LO_SHIPMODE VARCHAR(10),
  C_NAME VARCHAR(25),
  C_ADDRESS VARCHAR(25),
  C_CITY VARCHAR(10),
  C_NATION VARCHAR(15),
  C_REGION VARCHAR(12),
  C_PHONE VARCHAR(15),
  C_MKTSEGMENT VARCHAR(10),
  S_NAME VARCHAR(25),
  S_ADDRESS VARCHAR(25),
  S_CITY VARCHAR(10),
  S_NATION VARCHAR(15),
  S_REGION VARCHAR(12),
  S_PHONE VARCHAR(15),
  P_NAME VARCHAR(22),
  P_MFGR VARCHAR(6),
  P_CATEGORY VARCHAR(7),
  P_BRAND1 VARCHAR(9),
  P_COLOR VARCHAR(11),
  P_TYPE VARCHAR(25),
  P_SIZE NUMBER(38,0),
  P_CONTAINER VARCHAR(10),
    PRIMARY KEY (LO_ORDERKEY, LO_LINENUMBER) RELY
) AS SELECT * FROM SSB_SF{{SCALE}}_SRC.LINEORDER_FLAT ORDER BY LO_ORDERDATE;

DROP WAREHOUSE IF EXISTS {{SOLUTION_NAME}}_BENCH_WH_LOAD;
