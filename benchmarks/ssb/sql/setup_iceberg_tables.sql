-- SSB iceberg tables setup (per scale factor)
-- Requires: setup_source_views.sql (SSB views derived from SNOWFLAKE_SAMPLE_DATA.TPCH_SF<scale>).
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS {{SOLUTION_NAME}}_BENCH_DB;
USE DATABASE {{SOLUTION_NAME}}_BENCH_DB;

CREATE SCHEMA IF NOT EXISTS SSB_SF{{SCALE}}_ICE;
USE SCHEMA SSB_SF{{SCALE}}_ICE;

CREATE OR REPLACE WAREHOUSE {{SOLUTION_NAME}}_BENCH_WH_LOAD
  WAREHOUSE_SIZE = '{{LOAD_WH_SIZE}}'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = FALSE;

USE WAREHOUSE {{SOLUTION_NAME}}_BENCH_WH_LOAD;

-- LINEORDER / LINEORDER_FLAT are clustered by order date: every SSB query
-- restricts or groups by time, and the paper (section 3.2) suggests a time sort.

CREATE OR REPLACE ICEBERG TABLE LINEORDER
  CLUSTER BY (LO_ORDERDATE)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = '{{EXTERNAL_VOLUME}}'
  TARGET_FILE_SIZE = '{{TARGET_FILE_SIZE}}'
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.LINEORDER;

CREATE OR REPLACE ICEBERG TABLE CUSTOMER
  CLUSTER BY (C_CUSTKEY)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = '{{EXTERNAL_VOLUME}}'
  TARGET_FILE_SIZE = '{{TARGET_FILE_SIZE}}'
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.CUSTOMER;

CREATE OR REPLACE ICEBERG TABLE SUPPLIER
  CLUSTER BY (S_SUPPKEY)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = '{{EXTERNAL_VOLUME}}'
  TARGET_FILE_SIZE = '{{TARGET_FILE_SIZE}}'
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.SUPPLIER;

CREATE OR REPLACE ICEBERG TABLE PART
  CLUSTER BY (P_PARTKEY)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = '{{EXTERNAL_VOLUME}}'
  TARGET_FILE_SIZE = '{{TARGET_FILE_SIZE}}'
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.PART;

CREATE OR REPLACE ICEBERG TABLE DATES
  CLUSTER BY (D_DATEKEY)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = '{{EXTERNAL_VOLUME}}'
  TARGET_FILE_SIZE = '{{TARGET_FILE_SIZE}}'
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.DATES;

CREATE OR REPLACE ICEBERG TABLE LINEORDER_FLAT
  CLUSTER BY (LO_ORDERDATE)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = '{{EXTERNAL_VOLUME}}'
  TARGET_FILE_SIZE = '{{TARGET_FILE_SIZE}}'
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.LINEORDER_FLAT;

DROP WAREHOUSE IF EXISTS {{SOLUTION_NAME}}_BENCH_WH_LOAD;
