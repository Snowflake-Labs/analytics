-- Benchmark results storage (hybrid table, one row per benchmark run)
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS {{SOLUTION_NAME}}_BENCH_DB;
USE DATABASE {{SOLUTION_NAME}}_BENCH_DB;

CREATE SCHEMA IF NOT EXISTS SSB_RESULTS;
USE SCHEMA SSB_RESULTS;

CREATE SEQUENCE IF NOT EXISTS BENCHMARK_RUN_SEQ START = 1 INCREMENT = 1 ORDER;

CREATE HYBRID TABLE IF NOT EXISTS BENCHMARK_RUNS (
  BENCHMARK_RUN_ID           NUMBER        NOT NULL DEFAULT BENCHMARK_RUN_SEQ.NEXTVAL,
  BENCHMARK_RUN_TS           TIMESTAMP_NTZ NOT NULL,
  WAREHOUSE_TYPE             VARCHAR,
  TABLES_TYPE                VARCHAR,
  SCALE                      VARCHAR,
  WORKLOAD                   VARCHAR,
  TOTAL_QUERIES              NUMBER,
  SUCCESSFUL                 NUMBER,
  FAILED                     NUMBER,
  VALIDATION_PASSED          NUMBER,
  VALIDATION_FAILED          NUMBER,
  CLIENT_ELAPSED_S_TOTAL     NUMBER(18,6),
  CLIENT_ELAPSED_S_AVG       NUMBER(18,6),
  CLIENT_ELAPSED_S_MEDIAN    NUMBER(18,6),
  CLIENT_ELAPSED_S_MIN       NUMBER(18,6),
  CLIENT_ELAPSED_S_MAX       NUMBER(18,6),
  CLIENT_ELAPSED_S_P95       NUMBER(18,6),
  SERVER_ELAPSED_S_TOTAL     NUMBER(18,6),
  SERVER_ELAPSED_S_AVG       NUMBER(18,6),
  SERVER_ELAPSED_S_MEDIAN    NUMBER(18,6),
  SERVER_ELAPSED_S_MIN       NUMBER(18,6),
  SERVER_ELAPSED_S_MAX       NUMBER(18,6),
  SERVER_ELAPSED_S_P95       NUMBER(18,6),
  CONNECTION                 VARCHAR,
  DATABASE_NAME              VARCHAR,
  SCHEMA_NAME                VARCHAR,
  WAREHOUSE                  VARCHAR,
  WAREHOUSE_SIZE             VARCHAR,
  SERVER_VERSION             VARCHAR,
  TARGET_FILE_SIZE           VARIANT,
  RESULTS_JSON               VARIANT,
  PRIMARY KEY (BENCHMARK_RUN_ID)
);
