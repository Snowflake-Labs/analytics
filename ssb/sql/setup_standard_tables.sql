-- SSB standard tables setup (per scale factor)
-- Requires: setup_source_views.sql (SSB views derived from SNOWFLAKE_SAMPLE_DATA.TPCH_SF<scale>).
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS {{SOLUTION_NAME}}_BENCH_DB;
USE DATABASE {{SOLUTION_NAME}}_BENCH_DB;

CREATE SCHEMA IF NOT EXISTS SSB_SF{{SCALE}};
USE SCHEMA SSB_SF{{SCALE}};

CREATE OR REPLACE WAREHOUSE {{SOLUTION_NAME}}_BENCH_WH_LOAD
  WAREHOUSE_SIZE = '{{LOAD_WH_SIZE}}'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = FALSE;

USE WAREHOUSE {{SOLUTION_NAME}}_BENCH_WH_LOAD;

-- LINEORDER / LINEORDER_FLAT are clustered by order date: every SSB query
-- restricts or groups by time, and the paper (section 3.2) suggests a time sort.

CREATE OR REPLACE TABLE LINEORDER
  CLUSTER BY (LO_ORDERDATE)
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.LINEORDER ORDER BY LO_ORDERDATE;

CREATE OR REPLACE TABLE CUSTOMER
  CLUSTER BY (C_CUSTKEY)
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.CUSTOMER ORDER BY C_CUSTKEY;

CREATE OR REPLACE TABLE SUPPLIER
  CLUSTER BY (S_SUPPKEY)
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.SUPPLIER ORDER BY S_SUPPKEY;

CREATE OR REPLACE TABLE PART
  CLUSTER BY (P_PARTKEY)
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.PART ORDER BY P_PARTKEY;

CREATE OR REPLACE TABLE DATES
  CLUSTER BY (D_DATEKEY)
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.DATES ORDER BY D_DATEKEY;

CREATE OR REPLACE TABLE LINEORDER_FLAT
  CLUSTER BY (LO_ORDERDATE)
  AS SELECT * FROM SSB_SF{{SCALE}}_SRC.LINEORDER_FLAT ORDER BY LO_ORDERDATE;

DROP WAREHOUSE IF EXISTS {{SOLUTION_NAME}}_BENCH_WH_LOAD;
